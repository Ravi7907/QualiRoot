import os
import json

from dotenv import load_dotenv
from sqlalchemy import create_engine, text
from sqlalchemy.exc import SQLAlchemyError

# Load environment variables before creating the database engine
load_dotenv()

# PostgreSQL is the default database
DATABASE_URL = os.getenv(
    "DATABASE_URL",
    "postgresql+psycopg://postgres:password@localhost:5432/quali_root"
)

# SQLite compatibility (useful for existing installations)
connect_args = (
    {"check_same_thread": False}
    if DATABASE_URL.startswith("sqlite")
    else {}
)

engine = create_engine(
    DATABASE_URL,
    connect_args=connect_args,
    pool_pre_ping=True,
    pool_recycle=3600
)


def init_db():
    """Create the investigations table if it does not exist."""

    with engine.begin() as conn:

        if DATABASE_URL.startswith("sqlite"):

            conn.execute(text("""
                CREATE TABLE IF NOT EXISTS investigations (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    incident_title TEXT NOT NULL,
                    status TEXT NOT NULL,
                    payload TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """))

        else:

            conn.execute(text("""
                CREATE TABLE IF NOT EXISTS investigations (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    incident_title TEXT NOT NULL,
                    status TEXT NOT NULL,
                    payload TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """))


def save_investigation(payload: dict):
    """Save a new RCA investigation."""

    with engine.begin() as conn:

        result = conn.execute(
            text("""
                INSERT INTO investigations
                (incident_title, status, payload)
                VALUES (:title, :status, :payload)
                RETURNING id
            """),
            {
                "title": payload.get("incident_title")
                or "Untitled investigation",

                "status": payload.get("status", "Draft"),

                "payload": json.dumps(payload)
            }
        )

        return result.scalar_one()


def list_investigations():
    """Retrieve the latest 50 investigations."""

    with engine.begin() as conn:

        rows = conn.execute(
            text("""
                SELECT
                    id,
                    incident_title,
                    status,
                    created_at
                FROM investigations
                ORDER BY id DESC
                LIMIT 50
            """)
        ).mappings().all()

        return [dict(row) for row in rows]


def get_investigation(investigation_id: int):
    """Retrieve one complete investigation."""

    with engine.begin() as conn:

        row = conn.execute(
            text("""
                SELECT
                    id,
                    incident_title,
                    status,
                    payload,
                    created_at,
                    updated_at
                FROM investigations
                WHERE id = :id
            """),
            {"id": investigation_id}
        ).mappings().first()

        if not row:
            return None

        result = dict(row)

        payload = json.loads(result["payload"])

        payload["id"] = result["id"]
        payload["status"] = result["status"]
        payload["created_at"] = str(result["created_at"])
        payload["updated_at"] = str(result["updated_at"])

        return payload


def update_investigation(investigation_id: int, payload: dict):
    """Update an existing investigation."""

    with engine.begin() as conn:

        result = conn.execute(
            text("""
                UPDATE investigations
                SET
                    incident_title = :title,
                    status = :status,
                    payload = :payload,
                    updated_at = CURRENT_TIMESTAMP
                WHERE id = :id
            """),
            {
                "id": investigation_id,

                "title": payload.get("incident_title")
                or "Untitled investigation",

                "status": "Saved",

                "payload": json.dumps(payload)
            }
        )

        return result.rowcount > 0